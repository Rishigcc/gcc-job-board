-- ============================================================================
-- 001_job_board_foundation.sql
-- Stage 1 of the direct job board. Recruiter-side schema and the role model.
--
-- ADDITIVE ONLY. This migration creates new objects. It does not ALTER or
-- DROP any existing table, column, policy, function or trigger, so it cannot
-- affect the Q&A community, the 2,373 existing accounts, or the live site.
--
-- Rollback is in 001_job_board_foundation_rollback.sql.
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 1. TABLES
-- ---------------------------------------------------------------------------

-- Roles live in their own table, NOT as a column on profiles.
-- The existing "Users can update their own profile" policy is column-agnostic
-- (Postgres RLS is row-level, not column-level), so a role column on profiles
-- would let any signed-in user set their own role to 'admin' with one line in
-- the browser console. This table has no write policy at all.
--
-- A user with no row here is a candidate. We never write 'candidate' rows.
create table public.user_roles (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  role       text not null check (role in ('candidate','recruiter','admin')),
  created_at timestamptz not null default now()
);

create table public.recruiter_profiles (
  user_id           uuid primary key references auth.users(id) on delete cascade,
  recruiter_name    text not null,
  company_name      text not null,
  -- Always derived from the account's own email by the trigger below.
  -- A recruiter can never claim a domain they did not sign up with.
  email_domain      text not null,
  website           text,
  phone             text,
  -- Supplied by email reply and recorded by an admin. Not writable by the
  -- recruiter (see the column grants in section 5).
  gstin             text,
  is_verified       boolean not null default false,
  verified_at       timestamptz,
  is_suspended      boolean not null default false,
  suspended_at      timestamptz,
  terms_accepted_at timestamptz not null default now(),
  created_at        timestamptz not null default now()
);

-- The GCC doing the hiring, kept separate from the posting agency
-- (which is recruiter_profiles.company_name).
create table public.companies (
  id         uuid primary key default gen_random_uuid(),
  name       text not null,
  slug       text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  logo_url   text,
  created_at timestamptz not null default now()
);

create table public.jobs (
  id              bigint primary key generated by default as identity,
  company_id      uuid not null references public.companies(id),
  posted_by       uuid not null references auth.users(id) on delete cascade,
  title           text not null check (length(btrim(title)) between 3 and 200),
  -- Frozen after insert (not in the update grant) so a live URL can never
  -- break. The id in the public path disambiguates duplicate titles.
  slug            text not null check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  city            text not null,
  work_mode       text not null check (work_mode in ('onsite','hybrid','remote')),
  job_function    text not null,
  employment_type text not null
                  check (employment_type in ('full_time','part_time','contract','internship')),
  experience_min  int not null check (experience_min between 0 and 50),
  experience_max  int not null check (experience_max between 0 and 50),
  description     text not null check (length(btrim(description)) between 50 and 20000),
  apply_mode      text not null check (apply_mode in ('in_platform','external')),
  external_url    text,
  salary_min      int check (salary_min >= 0),
  salary_max      int check (salary_max >= 0),
  salary_currency text check (salary_currency in ('INR','USD')),
  salary_period   text check (salary_period in ('year','month')),
  openings        int check (openings between 1 and 999),
  skills          text[] not null default '{}',
  -- 'pending' and 'expired' are valid from day one so turning on an approval
  -- queue later is a screen, not a migration. Nothing sets either one.
  -- Expiry is DERIVED from expires_at (see job_is_public), never stored, so
  -- it needs no cron job and cannot drift.
  status          text not null default 'live'
                  check (status in ('live','pending','expired','closed','hidden')),
  published_at    timestamptz not null default now(),
  expires_at      timestamptz not null default now() + interval '30 days',
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now(),
  constraint experience_range check (experience_max >= experience_min),
  constraint external_needs_https_url
    check (apply_mode <> 'external' or external_url ~ '^https://'),
  constraint salary_range
    check (salary_min is null or salary_max is null or salary_max >= salary_min),
  constraint salary_needs_units
    check ((salary_min is null and salary_max is null)
           or (salary_currency is not null and salary_period is not null))
);


-- ---------------------------------------------------------------------------
-- 2. FUNCTIONS
--
-- They live in a `private` schema, NOT in `public`. Anything in `public` is
-- published by Supabase as a callable REST endpoint (/rest/v1/rpc/<name>).
-- These are internal plumbing for the policies below, so they are kept out of
-- the API surface entirely rather than exposed and then revoked -- an RLS
-- policy is evaluated with the querying user's own privileges, so revoking
-- EXECUTE on a function a policy calls would break the policy.
--
-- IMPORTANT: never add `private` to Settings -> API -> Exposed schemas in the
-- Supabase dashboard. That would publish all of these.
--
-- Created after the tables because `language sql` bodies are validated at
-- creation time. All are SECURITY DEFINER with a pinned search_path, because
-- a subquery inside a policy otherwise runs under the caller's own RLS and
-- silently returns the wrong answer: an anonymous visitor cannot see
-- recruiter_profiles, so a suspension check would always pass.
-- ---------------------------------------------------------------------------

create schema if not exists private;
revoke all on schema private from anon, authenticated;
grant usage on schema private to anon, authenticated;

create or replace function private.is_admin()
  returns boolean
  language sql stable security definer
  set search_path = public, pg_catalog
as $$
  select exists (
    select 1 from public.user_roles
    where user_id = auth.uid() and role = 'admin'
  );
$$;

-- A recruiter who may post: has a profile, is not suspended, and has clicked
-- the confirmation link. Supabase already withholds a session until the email
-- is confirmed; this states the same rule in the database so it holds no
-- matter how the API is called.
create or replace function private.is_active_recruiter()
  returns boolean
  language sql stable security definer
  set search_path = public, pg_catalog
as $$
  select exists (
    select 1
    from public.recruiter_profiles r
    join auth.users u on u.id = r.user_id
    where r.user_id = auth.uid()
      and not r.is_suspended
      and u.email_confirmed_at is not null
  );
$$;

create or replace function private.recruiter_is_verified(p_user uuid)
  returns boolean
  language sql stable security definer
  set search_path = public, pg_catalog
as $$
  select coalesce(
    (select is_verified from public.recruiter_profiles where user_id = p_user),
    false
  );
$$;

-- Counts only jobs that are actually live right now, so a recruiter who lets
-- jobs expire or closes them gets their allowance back.
create or replace function private.recruiter_live_job_count(p_user uuid)
  returns integer
  language sql stable security definer
  set search_path = public, pg_catalog
as $$
  select count(*)::int
  from public.jobs
  where posted_by = p_user
    and status = 'live'
    and expires_at > now();
$$;

-- The single definition of "the public can see this job". Expiry and
-- suspension are both derived here, which is why neither needs a cron job.
create or replace function private.job_is_public(
    p_status text,
    p_expires_at timestamptz,
    p_posted_by uuid)
  returns boolean
  language sql stable security definer
  set search_path = public, pg_catalog
as $$
  select p_status = 'live'
     and p_expires_at > now()
     and not exists (
       select 1 from public.recruiter_profiles r
       where r.user_id = p_posted_by and r.is_suspended
     );
$$;

-- Enforces the blocked-domain rule in the database as well as the form, so
-- creating a recruiter profile through the raw API cannot skip it.
-- Domain string match only. No MX lookup: real companies run their own
-- domains through Google Workspace and Zoho, and an MX check would reject them.
--
-- It also grants the recruiter role. This is the ONLY code path that ever
-- writes user_roles, and the only value it can ever write is 'recruiter'.
-- 'admin' can only be inserted from the Supabase dashboard.
create or replace function private.handle_new_recruiter()
  returns trigger
  language plpgsql security definer
  set search_path = public, pg_catalog
as $$
declare
  auth_domain text;
  blocked text[] := array[
    'gmail.com','googlemail.com','outlook.com','outlook.in','hotmail.com',
    'hotmail.co.uk','live.com','live.in','msn.com',
    'yahoo.com','yahoo.co.in','yahoo.in','ymail.com','rocketmail.com',
    'rediffmail.com','rediff.com',
    'proton.me','protonmail.com','protonmail.ch','pm.me',
    'icloud.com','me.com','mac.com',
    'zoho.com','zohomail.com','zoho.in',
    'aol.com','yandex.com','yandex.ru',
    'mail.com','gmx.com','gmx.net','inbox.com','fastmail.com','tutanota.com'
  ];
begin
  select lower(btrim(split_part(email, '@', 2)))
    into auth_domain
    from auth.users
   where id = new.user_id;

  if auth_domain is null or auth_domain = '' then
    raise exception 'No confirmed account found for this recruiter profile';
  end if;

  new.email_domain := auth_domain;

  if auth_domain = any(blocked) then
    raise exception
      'Free email providers cannot be used for recruiter accounts. Please sign up with your work email, or write to jobs@iworkatgcc.com.';
  end if;

  insert into public.user_roles (user_id, role)
  values (new.user_id, 'recruiter')
  on conflict (user_id) do nothing;

  return new;
end;
$$;

-- A local copy rather than reusing public.update_updated_at(), which the
-- Supabase security advisor flags for a mutable search_path. Touching that
-- function would mean editing an object the Q&A tables depend on, and this
-- migration does not edit anything that already exists.
create or replace function private.touch_updated_at()
  returns trigger
  language plpgsql
  set search_path = public, pg_catalog
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;


-- ---------------------------------------------------------------------------
-- 3. TRIGGERS
-- ---------------------------------------------------------------------------

create trigger recruiter_profiles_on_insert
  before insert on public.recruiter_profiles
  for each row execute function private.handle_new_recruiter();

create trigger jobs_touch_updated_at
  before update on public.jobs
  for each row execute function private.touch_updated_at();


-- ---------------------------------------------------------------------------
-- 4. ROW LEVEL SECURITY
-- The project's ensure_rls event trigger enables RLS on new public tables
-- automatically. Stated explicitly here so the file is self-documenting.
-- ---------------------------------------------------------------------------

alter table public.user_roles         enable row level security;
alter table public.recruiter_profiles enable row level security;
alter table public.companies          enable row level security;
alter table public.jobs               enable row level security;

-- user_roles: read your own row. That is the only thing the API can do.
-- No insert, update or delete policy exists, which under RLS means denied
-- for anon and authenticated alike.
create policy "read own role" on public.user_roles
  for select to authenticated using (auth.uid() = user_id);
create policy "admin reads all roles" on public.user_roles
  for select to authenticated using (private.is_admin());

-- recruiter_profiles
create policy "recruiter reads own profile" on public.recruiter_profiles
  for select to authenticated using (auth.uid() = user_id);
create policy "admin reads all recruiter profiles" on public.recruiter_profiles
  for select to authenticated using (private.is_admin());
create policy "recruiter creates own profile" on public.recruiter_profiles
  for insert to authenticated with check (auth.uid() = user_id);
create policy "recruiter updates own profile" on public.recruiter_profiles
  for update to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- companies
create policy "anyone reads companies" on public.companies
  for select to anon, authenticated using (true);
create policy "active recruiters add companies" on public.companies
  for insert to authenticated with check (private.is_active_recruiter());

-- jobs
create policy "anyone reads public jobs" on public.jobs
  for select to anon, authenticated
  using (private.job_is_public(status, expires_at, posted_by));
create policy "recruiter reads own jobs" on public.jobs
  for select to authenticated using (posted_by = auth.uid());
create policy "admin reads all jobs" on public.jobs
  for select to authenticated using (private.is_admin());

-- The posting cap. An unverified recruiter may hold at most 10 live jobs at
-- once; a verified one is uncapped. Enforced here rather than in the form, so
-- it cannot be bypassed by calling the API directly. With no approval queue
-- and no notifications, this is the control that stops someone posting two
-- hundred jobs overnight.
create policy "active recruiters post own jobs" on public.jobs
  for insert to authenticated
  with check (
    posted_by = auth.uid()
    and private.is_active_recruiter()
    and status = 'live'
    and (
      private.recruiter_is_verified(auth.uid())
      or private.recruiter_live_job_count(auth.uid()) < 10
    )
  );

-- A recruiter may edit and close their own job, but a job an admin hid can
-- never be edited back to life: 'hidden' is absent from both sides.
create policy "recruiter edits own job" on public.jobs
  for update to authenticated
  using  (posted_by = auth.uid() and status in ('live','closed'))
  with check (posted_by = auth.uid() and status in ('live','closed'));


-- ---------------------------------------------------------------------------
-- 5. COLUMN GRANTS
-- RLS decides which ROWS you may touch; it cannot restrict columns. These
-- grants do that. Postgres will not subtract a column from a table-wide
-- grant, so each table-level privilege is revoked first and the permitted
-- columns are granted back.
-- ---------------------------------------------------------------------------

-- Nothing writes user_roles through the API. Ever.
revoke insert, update, delete on public.user_roles from anon, authenticated;

-- A recruiter cannot verify, un-verify or suspend themselves, cannot change
-- the domain the trigger derived, and cannot write their own GSTIN.
revoke insert, update, delete on public.recruiter_profiles from anon, authenticated;
grant insert (user_id, recruiter_name, company_name, website, phone)
  on public.recruiter_profiles to authenticated;
grant update (recruiter_name, company_name, website, phone)
  on public.recruiter_profiles to authenticated;

-- Recruiters may name a company but not attach a logo to it.
revoke insert, update, delete on public.companies from anon, authenticated;
grant insert (name, slug) on public.companies to authenticated;

-- Deliberately not grantable: slug (a live URL must never change),
-- published_at, expires_at (otherwise a recruiter extends a posting
-- indefinitely on edit), created_at, posted_by, id.
revoke insert, update, delete on public.jobs from anon, authenticated;
grant insert (company_id, posted_by, title, slug, city, work_mode, job_function,
              employment_type, experience_min, experience_max, description,
              apply_mode, external_url, salary_min, salary_max, salary_currency,
              salary_period, openings, skills)
  on public.jobs to authenticated;
grant update (company_id, title, city, work_mode, job_function, employment_type,
              experience_min, experience_max, description, apply_mode,
              external_url, salary_min, salary_max, salary_currency,
              salary_period, openings, skills, status)
  on public.jobs to authenticated;

-- Function privileges. Default-deny, then grant EXECUTE only where a policy
-- actually needs it. job_is_public is granted to anon because the public job
-- read policy applies to signed-out visitors and calls it.
revoke all on all functions in schema private from public, anon, authenticated;
grant execute on function private.is_admin()                  to authenticated;
grant execute on function private.is_active_recruiter()        to authenticated;
grant execute on function private.recruiter_is_verified(uuid)  to authenticated;
grant execute on function private.recruiter_live_job_count(uuid) to authenticated;
grant execute on function private.job_is_public(text, timestamptz, uuid)
  to anon, authenticated;
-- The two trigger functions are never granted. Postgres checks privileges on
-- a trigger function when the trigger is created, not when it fires, so the
-- triggers keep working while nothing can call them directly.


