create index jobs_public_idx    on public.jobs (status, expires_at desc);
create index jobs_posted_by_idx on public.jobs (posted_by, status);
create index jobs_slug_idx      on public.jobs (slug);
create index jobs_filters_idx   on public.jobs (job_function, city);
