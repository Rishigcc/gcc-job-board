-- ===========================================================================
-- 007_applications.sql   --   stage 6, applying
--
-- THE ONE RULE THIS FILE EXISTS TO ENFORCE
--   A recruiter must never receive a candidate's name, email or resume path
--   in an API response. Not blurred in the UI, not masked client-side: the
--   data must not leave the database.
--
--   The way that is achieved here is blunt and checkable. public.applications
--   has NO select policy for recruiters at all. There is no row a recruiter
--   can read, so there is no column to leak. Stage 7 gives them what they are
--   allowed to see through narrow functions that return only permitted
--   columns -- it does not widen this table.
--
--   You can verify it from the browser with the public key: a recruiter
--   calling /rest/v1/applications gets [] no matter what they ask for.
--
-- RESUMES
--   A private storage bucket with NO policies on storage.objects, so no
--   client role can read or write it at all. Every upload goes through
--   /api/upload-resume, which runs with the service key and checks the
--   file's first bytes rather than trusting its name or its declared
--   content type. Every download will be a short-lived signed URL minted
--   server-side in stage 7.
--
-- CONSENT
--   consent_at is a timestamptz with a server default and is NOT in the
--   insert grant. A boolean would record that a box was ticked; this records
--   when, on the server's clock, and the client cannot set it.
--
-- ROLLBACK: 007_applications_rollback.sql
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. TABLE
-- ---------------------------------------------------------------------------
create table if not exists public.applications (
  id             bigint primary key generated by default as identity,
  job_id         bigint not null references public.jobs(id) on delete cascade,
  candidate_id   uuid   not null references auth.users(id) on delete cascade,

  -- Captured at application time, not read live from the profile. An
  -- application is a record of what someone said on the day; changing your
  -- display name later must not rewrite applications you already sent.
  full_name      text not null check (length(btrim(full_name)) between 2 and 120),
  email          text not null check (position('@' in email) > 1),
  phone          text check (phone is null or length(btrim(phone)) between 6 and 20),

  notice_period  text not null
                 check (notice_period in ('immediate','15_days','30_days',
                                          '60_days','90_days','serving_notice')),

  -- Path inside the private `resumes` bucket. A trigger below pins it to the
  -- candidate's own folder, so a granted column cannot be aimed at someone
  -- else's file.
  resume_path    text not null check (length(resume_path) between 10 and 400),

  consent_at     timestamptz not null default now(),

  -- 'withdrawn' is valid from day one so stage 8 is a screen, not a
  -- migration. Nothing sets it yet. "Closed" is NOT here: an application to
  -- a job that has ended is derived at read time from the job, exactly as
  -- job expiry is, so it cannot drift.
  status         text not null default 'applied'
                 check (status in ('applied','shortlisted','not_selected','withdrawn')),

  -- Delete-my-data (stage 8) anonymises the row and hard-deletes the file.
  -- The row survives so a recruiter's shortlist does not develop holes.
  anonymised_at  timestamptz,

  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),

  constraint one_application_per_job unique (job_id, candidate_id)
);

create index if not exists applications_job_idx       on public.applications (job_id, status);
create index if not exists applications_candidate_idx on public.applications (candidate_id, created_at desc);

-- ---------------------------------------------------------------------------
-- 2. FUNCTIONS  (private schema -- never add `private` to Exposed schemas)
-- ---------------------------------------------------------------------------

-- Is this job open to applications right now? Mirrors private.job_is_public
-- and adds the two things that only matter when applying.
create or replace function private.job_accepts_applications(p_job_id bigint)
  returns boolean
  language sql stable security definer
  set search_path = public, pg_catalog
as $$
  select exists (
    select 1
      from public.jobs j
      left join public.recruiter_profiles r on r.user_id = j.posted_by
     where j.id = p_job_id
       and j.status = 'live'
       and j.expires_at > now()
       and not coalesce(r.is_suspended, false)
       and j.apply_mode = 'in_platform'
       -- Applying to your own posting is not a thing. Someone may well be
       -- both a candidate and a recruiter -- that is an explicit decision --
       -- but not on the same role.
       and j.posted_by is distinct from auth.uid()
  );
$$;

-- A granted column can be set to anything, so the path is checked rather
-- than trusted. Every resume lives under the candidate's own user id.
create or replace function private.applications_guard()
  returns trigger
  language plpgsql security definer
  set search_path = public, pg_catalog
as $$
begin
  if new.resume_path !~ ('^' || new.candidate_id::text || '/') then
    raise exception
      'A resume can only be attached from your own upload. Please upload the file again.';
  end if;

  new.updated_at := now();
  return new;
end;
$$;

revoke all on function private.applications_guard() from public, anon, authenticated;
grant execute on function private.job_accepts_applications(bigint) to authenticated;

drop trigger if exists applications_guard on public.applications;
create trigger applications_guard
  before insert or update on public.applications
  for each row execute function private.applications_guard();

-- ---------------------------------------------------------------------------
-- 3. ROW LEVEL SECURITY
--
-- Note what is absent: there is no policy mentioning recruiters. That is the
-- whole security design, and it is easier to verify than any policy would be.
-- ---------------------------------------------------------------------------
alter table public.applications enable row level security;

create policy "candidate reads own applications" on public.applications
  for select to authenticated
  using (candidate_id = auth.uid());

create policy "admin reads all applications" on public.applications
  for select to authenticated
  using (private.is_admin());

create policy "candidate applies to an open job" on public.applications
  for insert to authenticated
  with check (
    candidate_id = auth.uid()
    and private.job_accepts_applications(job_id)
  );

-- No update policy and no delete policy. Withdrawing is stage 8;
-- delete-my-data anonymises rather than deletes, also stage 8.

-- ---------------------------------------------------------------------------
-- 4. GRANTS
--
-- Privileges and policies are independent locks. Both are set.
--
-- Deliberately absent from the insert grant:
--   consent_at    server clock, not the client's
--   status        the default 'applied' is the only value a candidate gets
--   anonymised_at stage 8, admin-side only
--   id, created_at, updated_at
-- ---------------------------------------------------------------------------
revoke all on public.applications from anon, authenticated;

grant select on public.applications to authenticated;

grant insert (job_id, candidate_id, full_name, email, phone,
              notice_period, resume_path)
  on public.applications to authenticated;

-- anon gets nothing at all: applying requires an account.

-- ---------------------------------------------------------------------------
-- 5. RESUME STORAGE
--
-- Private, 2 MB, PDF only. The bucket's own mime check is a backstop: the
-- declared content type comes from the client and can be a lie, so
-- /api/upload-resume reads the file's first bytes before it gets here.
--
-- NO POLICIES ARE CREATED ON storage.objects FOR THIS BUCKET. With RLS on
-- and no policy matching, anon and authenticated can neither read nor write
-- it. Only the service key can, and that lives in Vercel.
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('resumes', 'resumes', false, 2097152, array['application/pdf'])
on conflict (id) do update
  set public             = false,
      file_size_limit    = 2097152,
      allowed_mime_types = array['application/pdf'];

-- ---------------------------------------------------------------------------
-- 6. CHECKS -- expect: bucket row private, no storage policies, no recruiter
--    policy on applications.
-- ---------------------------------------------------------------------------
select id, public, file_size_limit, allowed_mime_types
  from storage.buckets where id = 'resumes';

select count(*) as storage_policies_on_resumes
  from pg_policies
 where schemaname = 'storage' and tablename = 'objects'
   and qual like '%resumes%';

select policyname, cmd
  from pg_policies
 where schemaname = 'public' and tablename = 'applications'
 order by cmd, policyname;
