-- ===========================================================================
-- 014_admin_audit.sql   --   stage 9, the admin action queue
--
-- WHAT CHANGED THE SHAPE OF THIS STAGE
--   Before writing it, I checked what an admin can actually do through the
--   app today. The answer is nothing:
--
--     recruiter_profiles   own-row INSERT/UPDATE and an admin SELECT. No
--                          admin UPDATE. Verifying and suspending have only
--                          ever been raw SQL in the dashboard.
--     companies            no UPDATE policy and no DELETE policy, for anyone.
--     jobs                 recruiter-only, and the update policy explicitly
--                          excludes 'hidden' on both sides.
--
--   So this is not a nicer interface for things that already work. It is the
--   first time these actions exist outside the SQL editor, which is why the
--   audit trail is written by the same function that performs the action
--   rather than by the page that calls it.
--
--   Also: jobs.status has only ever held 'live' in production. The 'hidden'
--   path has never run anywhere.
--
-- NO NEW POLICIES ON THE TABLES BEING ACTED ON
--   companies and recruiter_profiles still have no admin UPDATE policy after
--   this migration, and jobs still refuses 'hidden' to its poster. Every
--   write goes through a SECURITY DEFINER function gated on
--   private.is_admin(). Same shape as stage 7: the surface is a named list of
--   functions, not a widened table.
--
-- REVERSIBLE AND FINAL, HONESTLY SPLIT
--   Rishi's decision was that admin actions should be reversible. Three
--   cannot be, and saying so is better than a promise that is approximately
--   true:
--
--     reversible   verify/unverify, suspend/unsuspend, hide/unhide, rename
--     final        deleting an orphaned file, anonymising on request, and
--                  the nightly retention purge
--
--   "Reversible" here means an inverse action exists and the audit row
--   records what the previous value was. It is not a generic undo engine:
--   the four reversible actions are toggles, so the inverse is the other
--   button, and for a rename the audit row carries the old name.
--
-- ROLLBACK: 014_admin_audit_rollback.sql
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- 1. THE AUDIT TABLE
--
-- actor_id is NULLABLE, and null means the system rather than a person. The
-- nightly retention purge writes a row with no actor, which is the honest
-- representation: nobody decided it, a schedule did.
--
-- before/after hold enough to perform the inverse. They are jsonb rather than
-- typed columns because the targets differ -- a recruiter's two booleans, a
-- job's status, a company's name and slug -- and a column per target would
-- mean altering this table every time a new action is added.
--
-- target_id is text for the same reason: recruiters are uuids, jobs are
-- bigints, storage paths are strings.
-- ---------------------------------------------------------------------------
create table if not exists public.admin_audit (
  id          bigint primary key generated by default as identity,

  actor_id    uuid references auth.users(id) on delete set null,

  action      text not null
              check (action in (
                'recruiter_verified', 'recruiter_unverified',
                'recruiter_suspended', 'recruiter_unsuspended',
                'job_hidden', 'job_unhidden',
                'company_renamed',
                'orphan_file_deleted',
                'candidate_data_anonymised',
                'retention_purge'
              )),

  target_type text not null
              check (target_type in ('recruiter','job','company','candidate','storage','system')),
  target_id   text not null,

  -- Written by the function, for a person to read later. The point of an
  -- audit log is to be legible at the worst possible moment.
  summary     text not null check (length(btrim(summary)) between 3 and 500),

  before      jsonb,
  after       jsonb,

  reversible  boolean not null,

  created_at  timestamptz not null default now()
);

create index if not exists admin_audit_recent_idx on public.admin_audit (created_at desc);
create index if not exists admin_audit_target_idx on public.admin_audit (target_type, target_id);

-- ---------------------------------------------------------------------------
-- 2. RLS -- read-only, admin only, and no write path for anyone
--
-- No insert, update or delete policy and no write grant. Rows appear only
-- because a definer function below put them there, which is what makes
-- "the audit row cannot be skipped" true rather than a convention.
-- ---------------------------------------------------------------------------
alter table public.admin_audit enable row level security;

drop policy if exists "admin reads the audit log" on public.admin_audit;

create policy "admin reads the audit log" on public.admin_audit
  for select to authenticated
  using (private.is_admin());

revoke all on public.admin_audit from anon, authenticated;
grant select on public.admin_audit to authenticated;

-- ---------------------------------------------------------------------------
-- 3. THE WRITER
--
-- private, so nothing outside these functions can reach it. Every action
-- function calls it as its last act, inside the same transaction as the
-- change, so a committed change always has a committed audit row.
-- ---------------------------------------------------------------------------
create or replace function private.audit(
    p_actor       uuid,
    p_action      text,
    p_target_type text,
    p_target_id   text,
    p_summary     text,
    p_before      jsonb,
    p_after       jsonb,
    p_reversible  boolean
  )
  returns bigint
  language sql
  volatile
  security definer
  set search_path = public, pg_catalog
as $$
  insert into public.admin_audit
    (actor_id, action, target_type, target_id, summary, before, after, reversible)
  values
    (p_actor, p_action, p_target_type, p_target_id, p_summary, p_before, p_after, p_reversible)
  returning id;
$$;

revoke all on function private.audit(uuid, text, text, text, text, jsonb, jsonb, boolean)
  from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- 4. REVERSIBLE ACTIONS  --  admin-callable
--
-- Each one: refuse if not an admin, refuse if the target does not exist, do
-- nothing if the value is already what was asked for, then write the audit
-- row. "Already in that state" returns a sentence rather than raising,
-- because two admins clicking the same button is not an error.
-- ---------------------------------------------------------------------------
create or replace function public.admin_set_recruiter_verified(
    p_user     uuid,
    p_verified boolean
  )
  returns text
  language plpgsql
  volatile
  security definer
  set search_path = public, pg_catalog
as $$
declare
  v_before public.recruiter_profiles;
begin
  if not private.is_admin() then
    raise exception 'Only an administrator can do that.';
  end if;

  select * into v_before from public.recruiter_profiles where user_id = p_user;

  if not found then
    raise exception 'That recruiter account could not be found.';
  end if;

  if v_before.is_verified = p_verified then
    return case when p_verified then 'Already verified.' else 'Already unverified.' end;
  end if;

  update public.recruiter_profiles
     set is_verified = p_verified,
         verified_at = case when p_verified then now() else null end
   where user_id = p_user;

  perform private.audit(
    auth.uid(),
    case when p_verified then 'recruiter_verified' else 'recruiter_unverified' end,
    'recruiter',
    p_user::text,
    case when p_verified
      then v_before.company_name || ' verified — applicant details now visible, and the 10-live-roles cap is lifted'
      else v_before.company_name || ' verification removed — applicant details hidden again, and the cap reapplies'
    end,
    jsonb_build_object('is_verified', v_before.is_verified, 'verified_at', v_before.verified_at),
    jsonb_build_object('is_verified', p_verified),
    true
  );

  return case when p_verified then 'Verified.' else 'Verification removed.' end;
end;
$$;

