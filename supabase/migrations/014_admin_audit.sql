-- Hiding is the one action with no recruiter-side undo: migration 001's
-- update policy excludes 'hidden' on both sides, so a hidden job cannot be
-- edited or reopened by its poster. Only this function can put it back.
create or replace function public.admin_set_job_hidden(
    p_job_id bigint,
    p_hidden boolean
  )
  returns text
  language plpgsql
  volatile
  security definer
  set search_path = public, pg_catalog
as $$
declare
  v_title  text;
  v_status text;
  v_target text;
begin
  if not private.is_admin() then
    raise exception 'Only an administrator can do that.';
  end if;

  select j.title, j.status into v_title, v_status
    from public.jobs j where j.id = p_job_id;

  if not found then
    raise exception 'That role could not be found.';
  end if;

  if p_hidden and v_status = 'hidden' then
    return 'Already hidden.';
  end if;

  if not p_hidden and v_status <> 'hidden' then
    return 'That role is not hidden.';
  end if;

  -- Unhiding returns a job to 'live'. It does NOT revive an expired one:
  -- expiry is derived from expires_at at read time, so a job past its date
  -- stays invisible whatever its status says. That is deliberate -- unhiding
  -- should not silently extend a posting.
  v_target := case when p_hidden then 'hidden' else 'live' end;

  update public.jobs set status = v_target where id = p_job_id;

  perform private.audit(
    auth.uid(),
    case when p_hidden then 'job_hidden' else 'job_unhidden' end,
    'job',
    p_job_id::text,
    case when p_hidden
      then '"' || v_title || '" hidden — gone from the public board, and its poster cannot edit or reopen it'
      else '"' || v_title || '" unhidden — live again unless it has passed its closing date'
    end,
    jsonb_build_object('status', v_status),
    jsonb_build_object('status', v_target),
    true
  );

  return case when p_hidden then 'Hidden.' else 'Unhidden.' end;
end;
$$;

-- The new slug is computed by the CALLER, with the same companySlug() the
-- picker uses, and validated here. Reproducing that folding in SQL would mean
-- reimplementing Unicode NFKD normalisation in plpgsql and keeping two
-- implementations in step; validating what arrives is cheaper and cannot
-- drift. A slug that is valid but not what JS would have produced is
-- cosmetic -- nothing links to a company slug yet.
create or replace function public.admin_rename_company(
    p_company_id uuid,
    p_name       text,
    p_slug       text
  )
  returns text
  language plpgsql
  volatile
  security definer
  set search_path = public, pg_catalog
as $$
declare
  v_before public.companies;
  v_name   text := btrim(p_name);
  v_slug   text := btrim(lower(p_slug));
begin
  if not private.is_admin() then
    raise exception 'Only an administrator can do that.';
  end if;

  if length(v_name) < 2 or length(v_name) > 120 then
    raise exception 'A company name must be between 2 and 120 characters.';
  end if;

  if v_slug !~ '^[a-z0-9]+(-[a-z0-9]+)*$' then
    raise exception 'That name does not produce a usable web address. It needs at least one letter or number.';
  end if;

  select * into v_before from public.companies where id = p_company_id;

  if not found then
    raise exception 'That company could not be found.';
  end if;

  if v_before.name = v_name and v_before.slug = v_slug then
    return 'No change.';
  end if;

  if exists (select 1 from public.companies
              where slug = v_slug and id <> p_company_id) then
    raise exception
      'Another company already uses that web address. The two are probably the same employer, which needs a merge rather than a rename — not built yet, so write it down and leave both for now.';
  end if;

  update public.companies set name = v_name, slug = v_slug where id = p_company_id;

  perform private.audit(
    auth.uid(),
    'company_renamed',
    'company',
    p_company_id::text,
    '"' || v_before.name || '" renamed to "' || v_name || '"',
    jsonb_build_object('name', v_before.name, 'slug', v_before.slug),
    jsonb_build_object('name', v_name, 'slug', v_slug),
    true
  );

  return 'Renamed.';
end;
$$;

-- ---------------------------------------------------------------------------
-- 5. THE ORPHAN REPORT  --  reads storage, reports, deletes nothing
--
-- Stage 8 made deletion reliable for anyone who ASKS. This covers the files
-- belonging to people who never ask: an upload whose row write never
-- happened. storage.objects cannot be reached by any policy, so this needs a
-- definer function, and it is fully qualified because search_path is pinned.
--
-- Rishi's decision: it reports first and deletes second, with a human
-- reviewing the first few runs. So this function only lists.
-- ---------------------------------------------------------------------------
create or replace function public.admin_orphaned_resumes()
  returns table (
    resume_path text,
    folder      text,
    bytes       bigint,
    created_at  timestamptz
  )
  language sql
  stable
  security definer
  set search_path = public, pg_catalog
as $$
  select o.name,
         split_part(o.name, '/', 1),
         (o.metadata->>'size')::bigint,
         o.created_at
    from storage.objects o
   where o.bucket_id = 'resumes'
     and private.is_admin()
     and not exists (
       select 1 from public.candidate_resumes cr where cr.resume_path = o.name
     )
   order by o.created_at;
$$;

-- ---------------------------------------------------------------------------
-- 6. FINAL ACTIONS  --  service_role only, because a file has to go too
--
-- Same shape as stage 8, and for the same reason: deleting a resume is a row
-- AND an object in a private bucket, and only the service key can remove the
-- object. A database half callable from a browser would let a hand-written
-- RPC do one without the other.
--
-- These take p_actor and re-check that it is an admin, so a wrong actor
-- fails rather than being recorded as fact.
-- ---------------------------------------------------------------------------
create or replace function public.admin_anonymise_candidate_for(
    p_actor uuid,
    p_user  uuid
  )
  returns integer
  language plpgsql
  volatile
  security definer
  set search_path = public, pg_catalog
as $$
declare
  v_count integer;
begin
  if p_actor is null or not exists (
       select 1 from public.user_roles where user_id = p_actor and role = 'admin'
     ) then
    raise exception 'Only an administrator can do that.';
  end if;

  if p_user is null then
    raise exception 'No candidate given.';
  end if;

  delete from public.candidate_resumes where candidate_id = p_user;

  update public.applications
     set candidate_id  = null,
         full_name     = null,
         email         = null,
         phone         = null,
         notice_period = null,
         anonymised_at = now()
   where candidate_id = p_user
     and anonymised_at is null;

  get diagnostics v_count = row_count;

  perform private.audit(
    p_actor,
    'candidate_data_anonymised',
    'candidate',
    p_user::text,
    'Anonymised ' || v_count || ' application(s) and deleted the resume, on the candidate''s request',
    jsonb_build_object('applications', v_count),
    null,
    false
  );

  return v_count;
end;
$$;

-- The file is deleted by the endpoint; this records it. The row is written
-- after the object is gone, so a crash between the two loses the log entry
-- rather than the deletion -- and the orphan report simply stops listing it.
create or replace function public.admin_log_orphan_deleted(
    p_actor uuid,
    p_path  text
  )
  returns bigint
  language plpgsql
  volatile
  security definer
  set search_path = public, pg_catalog
as $$
begin
  if p_actor is null or not exists (
       select 1 from public.user_roles where user_id = p_actor and role = 'admin'
     ) then
    raise exception 'Only an administrator can do that.';
  end if;

  if p_path is null or length(btrim(p_path)) = 0 then
    raise exception 'No file given.';
  end if;

  return private.audit(
    p_actor,
    'orphan_file_deleted',
    'storage',
    p_path,
    'Deleted an orphaned resume file that no application referenced',
    jsonb_build_object('path', p_path),
    null,
    false
  );
end;
$$;

-- ---------------------------------------------------------------------------
-- 7. THE NIGHTLY SWEEP NOW LEAVES A RECORD
--
-- On Hobby, runtime logs survive about an hour, so a 02:00 UTC log line is
-- unreadable by morning. An audit row turns "did the sweep run" into a SQL
-- question answerable at any time.
--
-- actor_id is null: nobody decided this, a schedule did. A row is written
-- only when something was actually purged, so the table does not accumulate
-- 365 rows a year saying nothing happened.
-- ---------------------------------------------------------------------------
create or replace function public.purge_expired_applications(p_limit integer default 5000)
  returns integer
  language plpgsql
  volatile
  security definer
  set search_path = public, pg_catalog
as $$
declare
  v_count integer;
begin
  with doomed as (
    select a.id
      from public.applications a
      join public.jobs j on j.id = a.job_id
     where coalesce(j.closed_at, j.expires_at) < now() - interval '12 months'
     order by a.id
     limit greatest(coalesce(p_limit, 5000), 1)
  )
  delete from public.applications
   where id in (select id from doomed);

  get diagnostics v_count = row_count;

  if v_count > 0 then
    perform private.audit(
      null,
      'retention_purge',
      'system',
      'applications',
      'Deleted ' || v_count || ' application(s) past the 12-month retention period',
      jsonb_build_object('purged', v_count),
      null,
      false
    );
  end if;

  return v_count;
end;
$$;

-- ---------------------------------------------------------------------------
-- 8. GRANTS
--
-- The four reversible actions and the orphan report are admin-callable: they
-- check private.is_admin() themselves, so a non-admin calling them gets a
-- refusal rather than nothing.
--
-- The two final actions are service_role only, because each is half of a
-- pair with a storage deletion and neither half may happen alone.
-- ---------------------------------------------------------------------------
revoke all on function public.admin_set_recruiter_verified(uuid, boolean)       from public;
revoke all on function public.admin_set_recruiter_suspended(uuid, boolean)      from public;
revoke all on function public.admin_set_job_hidden(bigint, boolean)             from public;
revoke all on function public.admin_rename_company(uuid, text, text)            from public;
revoke all on function public.admin_orphaned_resumes()                          from public;
revoke all on function public.admin_anonymise_candidate_for(uuid, uuid)         from public;
revoke all on function public.admin_log_orphan_deleted(uuid, text)              from public;

grant execute on function public.admin_set_recruiter_verified(uuid, boolean)  to authenticated;
grant execute on function public.admin_set_recruiter_suspended(uuid, boolean) to authenticated;
grant execute on function public.admin_set_job_hidden(bigint, boolean)        to authenticated;
grant execute on function public.admin_rename_company(uuid, text, text)       to authenticated;
grant execute on function public.admin_orphaned_resumes()                     to authenticated;

grant execute on function public.admin_anonymise_candidate_for(uuid, uuid)    to service_role;
grant execute on function public.admin_log_orphan_deleted(uuid, text)         to service_role;

-- ---------------------------------------------------------------------------
-- 9. CHECKS -- every column must read PASS.
-- ---------------------------------------------------------------------------
with fns as (
  select count(*) as n,
         count(*) filter (where p.prosecdef) as definer,
         count(*) filter (where exists (
           select 1 from unnest(coalesce(p.proconfig,'{}')) c
            where c = 'search_path=public, pg_catalog')) as pinned
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
   where p.proname in ('admin_set_recruiter_verified','admin_set_recruiter_suspended',
                       'admin_set_job_hidden','admin_rename_company',
                       'admin_orphaned_resumes','admin_anonymise_candidate_for',
                       'admin_log_orphan_deleted','purge_expired_applications','audit')
     and n.nspname in ('public','private')
)
select
  case when (select n from fns) = 9 and (select definer from fns) = 9
        and (select pinned from fns) = 9
       then 'PASS' else 'FAIL — ' || (select n from fns) || ' of 9 found, '
                                  || (select definer from fns) || ' definer, '
                                  || (select pinned from fns) || ' pinned' end
    as c1_nine_functions,

  case when (select count(*) from pg_policies
              where schemaname = 'public' and tablename = 'admin_audit') = 1
        and (select count(*) from pg_policies
              where schemaname = 'public' and tablename = 'admin_audit' and cmd = 'SELECT') = 1
       then 'PASS' else 'FAIL — the audit log has a write policy' end
    as c2_audit_is_read_only,

  case when has_table_privilege('authenticated','public.admin_audit','SELECT')
        and not has_table_privilege('authenticated','public.admin_audit','INSERT')
        and not has_table_privilege('authenticated','public.admin_audit','UPDATE')
        and not has_table_privilege('authenticated','public.admin_audit','DELETE')
        and not has_table_privilege('anon','public.admin_audit','SELECT')
       then 'PASS' else 'FAIL — the audit log is writable or anon-readable' end
    as c3_audit_grants,

  case when has_function_privilege('authenticated','public.admin_set_recruiter_verified(uuid, boolean)','EXECUTE')
        and has_function_privilege('authenticated','public.admin_orphaned_resumes()','EXECUTE')
        and not has_function_privilege('authenticated','public.admin_anonymise_candidate_for(uuid, uuid)','EXECUTE')
        and not has_function_privilege('authenticated','public.admin_log_orphan_deleted(uuid, text)','EXECUTE')
        and not has_function_privilege('anon','public.admin_set_recruiter_verified(uuid, boolean)','EXECUTE')
       then 'PASS' else 'FAIL — the grant split is wrong' end
    as c4_grant_split,

  case when (select count(*) from pg_policies
              where schemaname = 'public' and tablename in ('companies','recruiter_profiles')
                and cmd in ('UPDATE','DELETE','ALL')
                and coalesce(qual,'') || coalesce(with_check,'') ilike '%is_admin%') = 0
       then 'PASS' else 'FAIL — an admin policy was added to a table instead of a function' end
    as c5_no_new_admin_policies,

  case when (select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace
              where n.nspname in ('public','private') and p.prokind = 'f'
                and not exists (select 1 from unnest(coalesce(p.proconfig,'{}')) c
                                 where c like 'search_path=%')) = 0
       then 'PASS' else 'FAIL — an unpinned function exists' end
    as c6_all_search_paths_pinned,

  case when (select count(*) from public.admin_audit) = 0
       then 'PASS' else 'note — ' || (select count(*) from public.admin_audit) || ' audit rows already' end
    as c7_audit_starts_empty;
